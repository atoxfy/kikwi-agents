package io.kikwiflow.agents.runtime.audit;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;

public final class Hashing {

    private Hashing() {
    }

    public static String sha256(String value) {
        try {
            byte[] digest = MessageDigest.getInstance("SHA-256").digest(value.getBytes(StandardCharsets.UTF_8));
            return HexFormat.of().formatHex(digest);
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    /** Os 12 primeiros hex do SHA-256, o mesmo formato de {@code iaPromptVersao} do demo de KYC. */
    public static String shortSha256(String value) {
        return sha256(value).substring(0, 12);
    }
}
